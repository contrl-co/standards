#!/usr/bin/env bash
#
# Vendor contrl-co/standards into a consumer repository at a pinned tag.
#
#     scripts/sync.sh <consumer-repo-path> <tag> [--force]
#
# Writes into the consumer:
#
#     .standards/                 vendored copy of standards/
#     .standards/VERSION          pinned tag and resolved commit
#     .standards/bin/             check-drift.sh, run by the consumer's CI
#     CLAUDE.md                   created only if absent, or with --force
#     AGENTS.md                   created only if absent, or with --force
#     .github/copilot-instructions.md
#     .cursor/rules/contrl-standards.mdc
#
# Agent instruction files are never overwritten without --force. They carry
# repository-specific sections that this script cannot regenerate.
#
set -euo pipefail

# STANDARDS_REPO exists so selftest.sh can point at a local clone. Consumers
# never set it.
readonly SOURCE_REPO="${STANDARDS_REPO:-https://github.com/contrl-co/standards.git}"
readonly VENDOR_DIR=".standards"

usage() {
  sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-1}"
}

[ $# -ge 2 ] || usage 1

consumer=$1
tag=$2
force=0
if [ "${3:-}" = "--force" ]; then
  force=1
fi

[ -d "$consumer/.git" ] || {
  echo "sync.sh: $consumer is not a git repository" >&2
  exit 1
}

consumer=$(cd "$consumer" && pwd)

workdir=$(mktemp -d)
trap 'rm -rf "$workdir"' EXIT

echo "fetching $SOURCE_REPO at $tag ..."
git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$tag" \
  "$SOURCE_REPO" "$workdir/standards"
commit=$(git -C "$workdir/standards" rev-parse HEAD)

# Replace rather than merge. A stale file left behind by a rename would pass
# the drift check on every run that does not happen to look for it.
rm -rf "${consumer:?}/$VENDOR_DIR"
mkdir -p "$consumer/$VENDOR_DIR/bin"
cp -R "$workdir/standards/standards/." "$consumer/$VENDOR_DIR/"

# scripts/vendored.txt is the single list of which gates reach consumers.
# check-drift.sh reads the same file from the pinned tag, so the two cannot
# disagree about what should be there.
while read -r script_name; do
  case "$script_name" in ''|\#*) continue ;; esac
  cp "$workdir/standards/scripts/$script_name" "$consumer/$VENDOR_DIR/bin/"
  chmod +x "$consumer/$VENDOR_DIR/bin/$script_name"
done < "$workdir/standards/scripts/vendored.txt"

cat > "$consumer/$VENDOR_DIR/VERSION" <<EOF
# Generated by contrl-co/standards scripts/sync.sh. Do not hand edit.
# Rerun sync.sh with a new tag to upgrade.
tag=$tag
commit=$commit
EOF

install_template() { # source, destination
  local source_path=$1 destination=$2
  mkdir -p "$(dirname "$consumer/$destination")"
  if [ -e "$consumer/$destination" ] && [ "$force" -eq 0 ]; then
    echo "  keep    $destination (exists, use --force to replace)"
    return
  fi
  cp "$workdir/standards/$source_path" "$consumer/$destination"
  echo "  write   $destination"
}

echo "vendoring into $consumer ..."
echo "  write   $VENDOR_DIR/ ($tag @ ${commit:0:7})"
install_template templates/CLAUDE.md CLAUDE.md
install_template templates/AGENTS.md AGENTS.md
install_template templates/github/copilot-instructions.md .github/copilot-instructions.md
install_template templates/cursor/contrl-standards.mdc .cursor/rules/contrl-standards.mdc

cat <<EOF

Done. Next:

  1. Review the diff in $consumer.
  2. Add the drift check to CI:

       standards-drift:
         runs-on: ubuntu-24.04
         steps:
           - uses: actions/checkout@<pinned-sha>
           - run: $VENDOR_DIR/bin/check-drift.sh

  3. Fill in the repository-specific section of CLAUDE.md and AGENTS.md.
EOF
